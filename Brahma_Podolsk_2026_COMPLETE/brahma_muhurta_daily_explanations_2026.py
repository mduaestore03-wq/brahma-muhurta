    start=datetime.fromisoformat(row['night15_start_iso'])
    end=datetime.fromisoformat(row['night15_end_iso'])
    sunrise=datetime.fromisoformat(row['sunrise_iso'])
    mid=start+(end-start)/2
    x=panchang(mid)
    at_sunrise=panchang(sunrise)
    night=float(row['night_duration_minutes']); unit=float(row['night_muhurta_minutes'])
    prev_night=float(prev['night_duration_minutes']) if prev else None
    night_comment, delta=daylight_notes(day,night,prev_night,unit)
    sunrise_shift=None if not prev else (sunrise-datetime.fromisoformat(prev['sunrise_iso'])-timedelta(days=1)).total_seconds()/60
    base=f"{row['brahma_night15_start']}–{row['brahma_night15_end']} (ночь/15), альтернативно {row['brahma_fixed48_start']}–{row['brahma_fixed48_end']} (48 минут). Восход {row['sunrise_local']}."
    if day==date(2026,10,25) and tz.key=='Europe/London':
        clock_comment="Великобритания переводит часы с BST на GMT: видимый скачок циферблатного времени назад на час не означает солнечного скачка."
    elif sunrise_shift is not None:
        if abs(sunrise_shift)<.35: clock_comment="Астрономический восход относительно предыдущей даты почти не изменился."
        else: clock_comment=f"Реальный восход (в абсолютном времени) сдвинулся на {abs(sunrise_shift):.1f} мин {'позже' if sunrise_shift>0 else 'раньше'} относительно предыдущего дня."
    else:clock_comment=""
    if day==date(2026,12,21):
        seasonal="Рядом с зимним солнцестоянием в Северном полушарии: минимальная продолжительность светового дня; момент солнцестояния не обязательно совпадает с самой длинной конкретной ночью."
    elif day>date(2026,12,21):
        seasonal="После солнцестояния дни постепенно удлиняются; сам восход ещё может становиться позже из-за уравнения времени."
    else:
        seasonal="До декабрьского солнцестояния световой день в Подольске сокращается; длительность ночи зависит от географической широты."
    moon=moon_note(x['t'],x['illum'])
    nak=NAKS[x['n']]
    transitions=transition_notes(start,end,tz)
    if transitions:
        trans="Важно: внутри самого интервала " + "; ".join(transitions)+". Нельзя описывать всё окно только одним состоянием панчанги."
    else: trans="Внутри указанного окна титхи, накшатра, йога и карана не сменяются."
