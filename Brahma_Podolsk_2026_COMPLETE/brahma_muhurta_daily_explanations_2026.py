def practice_for_panchang(x, day, has_transitions=False):
    """Компактная авторская рекомендация для каждого дня по теме накшатры и титхи.

    Не выражает доказанной причинности между календарными метками и эффектом практики.
    """
    focus, action = PRACTICE_BY_NAKSHATRA[x['n']]
    ti = x['t']
    key_id = 15 if ti == 29 else (14 if ti == 14 else ti % 15)
    subfocus, subaction = TITHI_PRACTICE_KEYS[key_id]
    focus_line = f"{focus}; дополнительная тема: {subfocus}"
    action_line = f"{action}. {subaction}."
    if has_transitions:
        action_line += " Если элементы панчанги сменяются в течение окна, упражнение из-за этого прерывать не нужно."
    # В Подольске нет сезонного перевода часов.
    if day == date(2026, 12, 21):
        action_line += " Отметь сезонный поворот, не делая выводов о физиологической «силе» этого часа."
    return focus_line, action_line


